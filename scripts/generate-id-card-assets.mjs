// Builds src/lib/id-card/assets.generated.ts from the brand logo and the fonts in
// assets/fonts, so the ID-card PDF can embed them without reading files at
// runtime (which Amplify's server bundle wouldn't include).
//   node scripts/generate-id-card-assets.mjs
import fs from "node:fs";

const svg = fs.readFileSync("public/brand/logo-full.svg", "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const transform = svg.match(/<g transform="([^"]+)"/)[1];
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

// Shapes before </g> are inside the transformed group (the chess symbol); the
// wordmark paths and tagline rules after it use the SVG's own coordinates.
const groupClose = svg.indexOf("</g>");
const shapes = [...svg.matchAll(/<(path|rect)\s[^>]*?\/?>/g)].map((m) => {
  const [tag, type] = m;
  const inGroup = m.index < groupClose;
  if (type === "path") return { type, d: attr(tag, "d"), fill: attr(tag, "fill"), inGroup };
  return {
    type,
    x: Number(attr(tag, "x")),
    y: Number(attr(tag, "y")),
    width: Number(attr(tag, "width")),
    height: Number(attr(tag, "height")),
    rx: Number(attr(tag, "rx") ?? 0),
    fill: attr(tag, "fill"),
    inGroup,
  };
});

const font = (file) => fs.readFileSync(`assets/fonts/${file}`).toString("base64");
const fonts = {
  interRegular: font("Inter-Regular.subset.ttf"),
  interSemiBold: font("Inter-SemiBold.subset.ttf"),
  interBold: font("Inter-Bold.subset.ttf"),
  tamilRegular: font("NotoSansTamil-Regular.ttf"),
  tamilBold: font("NotoSansTamil-Bold.ttf"),
};

const out = `// GENERATED by scripts/generate-id-card-assets.mjs — do not edit by hand.
// Fonts: Inter (Latin subset) and Noto Sans Tamil, SIL Open Font License 1.1
// (assets/fonts/OFL-*.txt). Logo: public/brand/logo-full.svg.

export const LOGO = ${JSON.stringify({ viewBox, transform, shapes })} as const;

export const FONT_BASE64 = ${JSON.stringify(fonts)} as const;
`;
fs.mkdirSync("src/lib/id-card", { recursive: true });
fs.writeFileSync("src/lib/id-card/assets.generated.ts", out);
console.log(
  `wrote src/lib/id-card/assets.generated.ts (${Math.round(out.length / 1024)} KB): ` +
    shapes.map((s) => `${s.type}${s.inGroup ? "(symbol)" : ""}`).join(" ")
);
